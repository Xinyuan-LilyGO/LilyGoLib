const storageKey = 'lilygo-flash-lab.language';

function initialLanguage() {
  try {
    const saved = localStorage.getItem(storageKey);
    if (Object.hasOwn(messages, saved)) return saved;
  } catch { /* Browser storage may be unavailable. */ }
  for (const candidate of navigator.languages || [navigator.language]) {
    const base = String(candidate).toLowerCase().split('-')[0];
    if (base === 'zh') return 'zh-CN';
    if (base === 'ja' || base === 'en') return base;
  }
  return 'en';
}

let language = initialLanguage();

export function getLanguage() { return language; }

export function setLanguage(value) {
  if (!Object.hasOwn(messages, value)) return;
  language = value;
  try { localStorage.setItem(storageKey, value); }
  catch { /* Keep the current language even when persistence is unavailable. */ }
}

export function t(key, params = {}) {
  const template = messages[language][key] ?? messages.en[key] ?? key;
  return template.replace(/\{(\w+)\}/g, (_match, name) => {
    const value = params[name];
    return value && typeof value === 'object' && value.key
      ? t(value.key, value.params)
      : String(value ?? '');
  });
}
